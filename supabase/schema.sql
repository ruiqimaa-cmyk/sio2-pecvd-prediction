create table if not exists prediction_logs (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  model_version text not null,
  electrode_type text not null,
  x_cm numeric,
  y_cm numeric,
  pressure_torr numeric,
  pressure_pa numeric,
  predicted_film_thickness_nm numeric,
  predicted_deposition_rate_nm_min numeric,
  predicted_uniformity_parameter numeric,
  confidence_note text,
  client_metadata jsonb
);

alter table prediction_logs enable row level security;

drop policy if exists "Allow anonymous inserts for prediction logs" on prediction_logs;

create policy "Allow anonymous inserts for prediction logs"
on prediction_logs
for insert
to anon
with check (true);

drop policy if exists "Allow anonymous reads for prediction logs" on prediction_logs;

create policy "Allow anonymous reads for prediction logs"
on prediction_logs
for select
to anon
using (true);
